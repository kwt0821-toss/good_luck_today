import type { Cat, Grade } from "../types";
import { catImageUrl } from "./catArt";

function cat(
  index: number,
  name: string,
  grade: Grade,
  description: string,
): Cat {
  const id = `cat_${String(index).padStart(3, "0")}`;
  return {
    id,
    name,
    grade,
    imageUrl: catImageUrl(id, grade),
    description,
  };
}

