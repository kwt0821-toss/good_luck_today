/**
 * Cut the opaque part of the four view-mode world images, plus 4px of padding,
 * into `*-crop.webp`. Originals stay. Writes the boxes the app positions with.
 *
 *   node scripts/crop-room-layers.mjs
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const PAD = 4;
const DIR = "public/assets/room/world";
const FILES = [
  "room-frame-view.webp",
  "string-lights.webp",
  "lamp-glow-additive.webp",
  "front-puffs-view.webp",
];

function opaqueBox(data, width, height) {
  let minX = width;
  let minY = height;
  let maxX = -1;
  let maxY = -1;
  for (let i = 0; i < width * height; i += 1) {
    if (data[i * 4 + 3] === 0) continue;
    const x = i % width;
    const y = (i - x) / width;
    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x > maxX) maxX = x;
    if (y > maxY) maxY = y;
  }
  if (maxX < 0) return null;
  const left = Math.max(0, minX - PAD);
  const top = Math.max(0, minY - PAD);
  const right = Math.min(width, maxX + 1 + PAD);
  const bottom = Math.min(height, maxY + 1 + PAD);
  return { left, top, width: right - left, height: bottom - top, sw: width, sh: height };
}

async function maxAlpha(buffer) {
  const { data, info } = await sharp(buffer).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let max = 0;
  for (let i = 3; i < data.length; i += 4) if (data[i] > max) max = data[i];
  return { max, width: info.width, height: info.height };
}

async function encodeCrop(source, box, originalBytes) {
  const cropped = await sharp(source)
    .extract({ left: box.left, top: box.top, width: box.width, height: box.height })
    .png()
    .toBuffer();
  for (const quality of [90, 84, 78, 72, 66, 60]) {
    const buf = await sharp(cropped).webp({ quality, alphaQuality: 100, effort: 4 }).toBuffer();
    const alpha = await maxAlpha(buf);
    if (buf.length <= originalBytes && alpha.max > 0) return { buf, quality, alpha: alpha.max };
  }
  const buf = await sharp(cropped).webp({ lossless: true }).toBuffer();
  const alpha = await maxAlpha(buf);
  return { buf, quality: "lossless", alpha: alpha.max };
}

const crops = [];
for (const name of FILES) {
  const source = path.join(DIR, name);
  const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const box = opaqueBox(data, info.width, info.height);
  if (!box) throw new Error(`${name} has no opaque pixels`);
  const originalBytes = fs.statSync(source).size;
  const encoded = await encodeCrop(source, box, originalBytes);
  const outName = name.replace(/\.webp$/, "-crop.webp");
  const outPath = path.join(DIR, outName);
  fs.writeFileSync(outPath, encoded.buf);
  crops.push({ name, outName, box, bytes: encoded.buf.length, originalBytes, quality: encoded.quality, alpha: encoded.alpha });
  console.log(
    `${outName} ${box.left},${box.top} ${box.width}x${box.height} q=${encoded.quality} ${encoded.buf.length}B (was ${originalBytes}B) alpha ${encoded.alpha}`,
  );
}

const body = crops
  .map((crop) => {
    const { box } = crop;
    return `  ${JSON.stringify(crop.name)}: { file: ${JSON.stringify(crop.outName)}, x: ${box.left}, y: ${box.top}, w: ${box.width}, h: ${box.height}, sw: ${box.sw}, sh: ${box.sh} },`;
  })
  .join("\n");

const ts = `/** Generated by scripts/crop-room-layers.mjs. Do not edit the boxes by hand. */

export type LayerCrop = {
  file: string;
  x: number;
  y: number;
  w: number;
  h: number;
  sw: number;
  sh: number;
};

export const LAYER_CROPS: Record<string, LayerCrop> = {
${body}
};

export function layerCrop(src: string): LayerCrop | null {
  const name = src.split("/").pop() ?? src;
  return LAYER_CROPS[name] ?? null;
}

/** Place a cropped image in the same world slot. Shift is in world pixels, added as a percent of the world. */
export function layerBoxStyle(
  crop: LayerCrop,
  shift?: { x: number; y: number; worldW: number; worldH: number },
): { left: string; top: string; width: string; height: string } {
  const dx = shift ? (shift.x / shift.worldW) * 100 : 0;
  const dy = shift ? (shift.y / shift.worldH) * 100 : 0;
  return {
    left: \`\${(crop.x / crop.sw) * 100 + dx}%\`,
    top: \`\${(crop.y / crop.sh) * 100 + dy}%\`,
    width: \`\${(crop.w / crop.sw) * 100}%\`,
    height: \`\${(crop.h / crop.sh) * 100}%\`,
  };
}
`;

fs.writeFileSync("src/lib/roomRender/layerCrops.ts", ts);
console.log("wrote src/lib/roomRender/layerCrops.ts");
