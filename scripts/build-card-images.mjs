/**
 * Resize each card front into two WebPs.
 * Sources are the existing full-size fronts (660×1027 WebP — there is no PNG set).
 * Those files stay put. The app reads only the files written here.
 *
 *   public/assets/dex/opt/{id}.webp        width 720 (no upscale), quality 82
 *   public/assets/dex/opt/{id}@thumb.webp  width 200, quality 75
 */
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.error("sharp가 설치되어 있지 않습니다. npm install 한 뒤 npm run cards:webp 를 실행하세요.");
  process.exit(1);
}

const root = path.resolve(import.meta.dirname, "..");
const catalogPath = path.join(root, "public/assets/dex/cards.json");
const outDir = path.join(root, "public/assets/dex/opt");
const versionPath = path.join(root, "src/lib/cardAssetVersion.ts");

const catalog = JSON.parse(await readFile(catalogPath, "utf8"));
await mkdir(outDir, { recursive: true });

const hashes = [];

for (const card of catalog.cards) {
  const folder = card.type;
  const source = path.join(root, "public/assets/dex/cards", folder, `${card.id}_front.webp`);
  const largeName = `${card.id}.webp`;
  const thumbName = `${card.id}@thumb.webp`;
  const largePath = path.join(outDir, largeName);
  const thumbPath = path.join(outDir, thumbName);

  await sharp(source)
    .resize({ width: 720, withoutEnlargement: true })
    .webp({ quality: 82 })
    .toFile(largePath);
  await sharp(source)
    .resize({ width: 200, withoutEnlargement: true })
    .webp({ quality: 75 })
    .toFile(thumbPath);

  card.front = `opt/${largeName}`;
  card.thumb = `opt/${thumbName}`;

  const [largeBuf, thumbBuf] = await Promise.all([readFile(largePath), readFile(thumbPath)]);
  hashes.push(createHash("sha1").update(largeBuf).update(thumbBuf).digest());
}

catalog.imageSizes = {
  "front/back": "source 660x1027; app large max width 720 webp q82",
  thumb: "200px wide webp q75",
};

await writeFile(catalogPath, `${JSON.stringify(catalog, null, 1)}\n`);

const frameDir = path.join(root, "public/assets/frames");
for (const name of (await readdir(frameDir)).filter((file) => /^(frame|window)-.+\.webp$/.test(file)).sort()) {
  hashes.push(createHash("sha1").update(await readFile(path.join(frameDir, name))).digest());
}

async function webpFiles(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await webpFiles(full)));
    else if (entry.name.endsWith(".webp")) found.push(full);
  }
  return found;
}

const artDir = path.join(root, "public/assets/cards-art");
for (const file of (await webpFiles(artDir)).sort()) {
  hashes.push(createHash("sha1").update(await readFile(file)).digest());
}

// Bump when image bytes are unchanged but clients must drop immutable copies.
const CACHE_GENERATION = "5";
const version = createHash("sha1")
  .update(Buffer.concat(hashes))
  .update(CACHE_GENERATION)
  .digest("hex")
  .slice(0, 10);

await writeFile(
  versionPath,
  `/** Generated by scripts/build-card-images.mjs. Content hash of the opt WebPs. */\nexport const CARD_ASSET_VERSION = "${version}";\n`,
);

console.log(`wrote ${catalog.cards.length} cards, v=${version}`);
